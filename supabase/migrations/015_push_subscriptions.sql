-- ============ جدول اشتراكات Push Notifications ============
-- يخزن اشتراكات Web Push للمستخدمين لإرسال إشعارات عند إضافة محتوى جديد

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at bigint not null
);

create index if not exists idx_push_subscriptions_user_id on public.push_subscriptions(user_id);

-- فهرس فريد على endpoint لدعم upsert مع onConflict: 'endpoint'
create unique index if not exists idx_push_subscriptions_endpoint on public.push_subscriptions(endpoint);

-- تمكين RLS
alter table public.push_subscriptions enable row level security;

-- سياسة: المستخدم يرى اشتراكاته فقط، الخدمة تدير הכל
create policy "Users can view own subscriptions" on public.push_subscriptions
  for select using (auth.uid() = user_id);

create policy "Users can insert own subscriptions" on public.push_subscriptions
  for insert with check (auth.uid() = user_id);

create policy "Users can delete own subscriptions" on public.push_subscriptions
  for delete using (auth.uid() = user_id);

-- خدمة الحافة (service_role) تدير הכל بدون قيود
grant all on public.push_subscriptions to service_role;