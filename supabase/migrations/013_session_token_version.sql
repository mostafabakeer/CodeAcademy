-- ============ نسخة جلسات المستخدم (إبطال التوكنات) ============
-- كل توكن JWT يحمل الحقل `tv` (token_version لحظة الإصدار).
-- عند "خروج من كل الأجهزة" أو تغيير كلمة السر نزيد الرقم، فتبطل كل
-- التوكنات الصادرة قبله — حتى لو كانت منسوخة على جهاز آخر.
--
-- الافتراضي 0، والتوكنات القديمة (بدون tv) تُقرأ كـ 0 فتظل صالحة
-- إلى أن يحدث أول إبطال. آمن لإعادة التنفيذ.

alter table public.users
  add column if not exists token_version bigint not null default 0;

comment on column public.users.token_version is
  'يزداد لإبطال كل جلسات المستخدم فوراً (logout-all / تغيير كلمة السر).';
