-- Add essay questions without changing the existing MCQ defaults.
alter table public.questions
  add column if not exists question_type text not null default 'mcq',
  add column if not exists points integer not null default 1;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'questions_question_type_check'
      and conrelid = 'public.questions'::regclass
  ) then
    alter table public.questions
      add constraint questions_question_type_check
      check (question_type in ('mcq', 'essay'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'questions_points_positive_check'
      and conrelid = 'public.questions'::regclass
  ) then
    alter table public.questions
      add constraint questions_points_positive_check
      check (points > 0);
  end if;
end;
$$;

-- Each essay-bearing attempt remains independently reviewable, even after later retakes.
create table if not exists public.exam_submissions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  attempt_number integer not null check (attempt_number > 0),
  status text not null default 'pending_review'
    check (status in ('pending_review', 'graded')),
  mcq_score integer not null default 0 check (mcq_score between 0 and 100),
  mcq_correct integer not null default 0 check (mcq_correct >= 0),
  mcq_total integer not null default 0 check (mcq_total >= 0),
  mcq_answers jsonb not null default '{}'::jsonb,
  essay_questions jsonb not null default '[]'::jsonb,
  essay_answers jsonb not null default '{}'::jsonb,
  essay_grades jsonb not null default '{}'::jsonb,
  score integer check (score between 0 and 100),
  earned_points numeric(8, 2) not null default 0 check (earned_points >= 0),
  maximum_points numeric(8, 2) not null default 0 check (maximum_points >= 0),
  baseline_best integer not null default 0 check (baseline_best between 0 and 100),
  submitted_at bigint not null,
  graded_at bigint,
  unique (user_id, exam_id, attempt_number)
);

create index if not exists idx_exam_submissions_exam_status_submitted
  on public.exam_submissions (exam_id, status, submitted_at desc);
create index if not exists idx_exam_submissions_user_exam_submitted
  on public.exam_submissions (user_id, exam_id, submitted_at desc);
create unique index if not exists idx_exam_submissions_one_pending_per_user_exam
  on public.exam_submissions (user_id, exam_id)
  where status = 'pending_review';

alter table public.exam_submissions enable row level security;
revoke all on public.exam_submissions from anon, authenticated;
grant all on public.exam_submissions to service_role;
grant usage, select on sequence public.exam_submissions_id_seq to service_role;

-- Publish the final result and its reviewed essay scores as one transaction.
create or replace function public.approve_essay_submission(
  p_submission_id bigint,
  p_essay_grades jsonb,
  p_score integer,
  p_result_score integer,
  p_earned_points numeric,
  p_maximum_points numeric,
  p_best integer,
  p_attempts integer,
  p_result_correct integer,
  p_result_total integer,
  p_result_answers jsonb,
  p_history jsonb,
  p_result_at bigint,
  p_graded_at bigint
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  submission public.exam_submissions%rowtype;
begin
  select *
    into submission
    from public.exam_submissions
   where id = p_submission_id
   for update;

  if not found then
    raise exception 'Essay submission % not found', p_submission_id;
  end if;

  update public.exam_submissions
     set status = 'graded',
         essay_grades = p_essay_grades,
         score = p_score,
         earned_points = p_earned_points,
         maximum_points = p_maximum_points,
         graded_at = p_graded_at
   where id = p_submission_id;

  insert into public.exam_results (
    user_id, exam_id, best, score, correct, total, attempts, answers, history, at
  ) values (
    submission.user_id,
    submission.exam_id,
    p_best,
    p_result_score,
    p_result_correct,
    p_result_total,
    p_attempts,
    p_result_answers,
    p_history,
    p_result_at
  )
  on conflict (user_id, exam_id) do update
     set best = excluded.best,
         score = excluded.score,
         correct = excluded.correct,
         total = excluded.total,
         attempts = excluded.attempts,
         answers = excluded.answers,
         history = excluded.history,
         at = excluded.at;
end;
$$;

revoke all on function public.approve_essay_submission(bigint, jsonb, integer, integer, numeric, numeric, integer, integer, integer, integer, jsonb, jsonb, bigint, bigint)
  from public, anon, authenticated;
grant execute on function public.approve_essay_submission(bigint, jsonb, integer, integer, numeric, numeric, integer, integer, integer, integer, jsonb, jsonb, bigint, bigint)
  to service_role;
